    @GetMapping("/export")
    public ResponseEntity<byte[]> exportReport(
            @RequestParam String type,
            @RequestParam(defaultValue = "excel") String format,
            HttpSession session) {

        String role = (String) session.getAttribute("userRole");
        if (role == null || !ALLOWED_ROLES.contains(role)) {
            return ResponseEntity.status(403).build();
        }

        String area = type == null ? "" : type.toLowerCase().trim();
        String fmt = format == null ? "excel" : format.toLowerCase().trim();
        if (!EXPORT_AREAS.contains(area)) {
            return ResponseEntity.badRequest().build();
        }

        try {
            byte[] fileBytes = switch (area) {
                case "attendance" -> hrExportService.exportAttendance(fmt);
                case "leave" -> hrExportService.exportLeave(fmt);
                case "recruitment" -> hrExportService.exportRecruitment(fmt);
                case "holidays" -> hrExportService.exportHolidays(fmt);
                case "documents" -> hrExportService.exportDocuments(fmt);
                default -> throw new IllegalArgumentException("Unknown export area: " + area);
            };

            String extension = switch (fmt) {
                case "csv" -> "csv";
                case "pdf" -> "pdf";
                case "docx", "word" -> "docx";
                default -> "xlsx";
            };

            MediaType mediaType = switch (fmt) {
                case "csv" -> MediaType.parseMediaType("text/csv");
                case "pdf" -> MediaType.APPLICATION_PDF;
                case "docx", "word" -> MediaType.parseMediaType(
                        "application/vnd.openxmlformats-officedocument.wordprocessingml.document");
                default -> MediaType.parseMediaType(
                        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet");
            };

            String filename = area + "-report." + extension;

            HttpHeaders headers = new HttpHeaders();
            headers.setContentDisposition(
                    org.springframework.http.ContentDisposition.attachment().filename(filename).build());

            return ResponseEntity.ok()
                    .headers(headers)
                    .contentType(mediaType)
                    .body(fileBytes);

        } catch (Exception e) {
            logger.error("Error exporting {} report as {}: {}", area, fmt, e.getMessage(), e);
            return ResponseEntity.internalServerError().build();
        }
    }

    private record FileRequest(String area, String format) {}

    private FileRequest detectFileRequest(String message) {
        String lower = message.toLowerCase().trim();
        if (message.trim().endsWith("?") || isInformationalQuery(lower)) {
            return null; // it's a question, not a download/export command
        }
        // Must contain a format keyword OR a strong action keyword
        boolean hasFormat = FORMAT_KEYWORDS.stream().anyMatch(lower::contains);
        boolean hasAction = ACTION_KEYWORDS.stream().anyMatch(lower::contains);
        if (!hasFormat && !hasAction) {
            return null; // Not a file request
        }

        // Must also mention a data area
        String area = null;
        if (lower.contains("attendance")) area = "attendance";
        else if (lower.contains("leave")) area = "leave";
        else if (lower.contains("recruit") || lower.contains("job") || lower.contains("application")) area = "recruitment";
        else if (lower.contains("holiday")) area = "holidays";
        else if (lower.contains("document")) area = "documents";

        if (area == null) return null;

        String format = "excel"; // default
        if (lower.contains("csv")) format = "csv";
        else if (lower.contains("pdf")) format = "pdf";
        else if (lower.contains("word") || lower.contains("docx")) format = "docx";
        else if (lower.contains("excel") || lower.contains("xlsx")) format = "excel";

        return new FileRequest(area, format);
    }

    private String capitalize(String s) {
        if (s == null || s.isEmpty()) return s;
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    private String buildHrContext() {
        StringBuilder ctx = new StringBuilder();

        // --- Employees (fetched once, reused by later sections) ---
        List<Employee> allEmployees = new ArrayList<>();
        Map<String, String> employeeNameById = new HashMap<>();
        try {
            allEmployees = employeeService.getAllEmployees();
            long activeCount = allEmployees.stream().filter(Employee::isActive).count();

            employeeNameById = allEmployees.stream()
                    .collect(Collectors.toMap(Employee::getEmployeeId, e ->
                                    e.getEmployeeName() != null ? e.getEmployeeName() : e.getEmployeeId(),
                            (a, b) -> a));

            ctx.append("== EMPLOYEES ==\n");
            ctx.append("Total employees: ").append(allEmployees.size()).append("\n");
            ctx.append("Active: ").append(activeCount)
                    .append(" | Inactive: ").append(allEmployees.size() - activeCount).append("\n");

            Map<String, Long> byDept = allEmployees.stream()
                    .filter(e -> e.getDepartment() != null)
                    .collect(Collectors.groupingBy(Employee::getDepartment, Collectors.counting()));
            byDept.forEach((dept, count) -> ctx.append(" - ").append(dept).append(": ").append(count).append("\n"));

            long onboardingPending = allEmployees.stream()
                    .filter(e -> e.getOnboardingStatus() != null &&
                            (e.getOnboardingStatus().equals("NOT_STARTED") ||
                                    e.getOnboardingStatus().equals("DOCUMENTS_PENDING") ||
                                    e.getOnboardingStatus().equals("DOCUMENTS_SUBMITTED") ||
                                    e.getOnboardingStatus().equals("IN_PROGRESS")))
                    .count();
            ctx.append("Employees currently in onboarding: ").append(onboardingPending).append("\n\n");
        } catch (Exception e) {
            logger.error("Context section failed: employees", e);
            ctx.append("== EMPLOYEES (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Today's attendance ---
        try {
            List<Map<String, Object>> todayAttendance = attendanceService.getTodayAllAttendances();
            long present = todayAttendance.stream()
                    .filter(a -> "ACTIVE".equals(a.get("status")) || "BREAK".equals(a.get("status")))
                    .count();
            long checkedOut = todayAttendance.stream()
                    .filter(a -> a.get("checkOutTime") != null)
                    .count();

            ctx.append("== TODAY'S ATTENDANCE ==\n");
            ctx.append("Total records today: ").append(todayAttendance.size()).append("\n");
            ctx.append("Present/On break: ").append(present).append("\n");
            ctx.append("Checked out: ").append(checkedOut).append("\n");
            ctx.append("No attendance record (likely absent): ")
                    .append(allEmployees.size() - todayAttendance.size()).append("\n\n");
        } catch (Exception e) {
            logger.error("Context section failed: today's attendance", e);
            ctx.append("== TODAY'S ATTENDANCE (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Pending leave requests ---
        try {
            List<LeaveRequest> pendingLeaves = leaveRequestRepository.findByStatus("PENDING");
            ctx.append("== LEAVE - PENDING REQUESTS ==\n");
            ctx.append("Pending leave requests: ").append(pendingLeaves.size()).append("\n");
            for (LeaveRequest lr : pendingLeaves) {
                String name = employeeNameById.getOrDefault(lr.getEmployeeId(), lr.getEmployeeId());
                ctx.append(" - ").append(name).append(" (").append(lr.getEmployeeId()).append(")")
                        .append(" | ID: ").append(lr.getId())
                        .append(" | ").append(lr.getLeaveType())
                        .append(" | ").append(lr.getStartDate()).append(" to ").append(lr.getEndDate())
                        .append(" | ").append(lr.getTotalDays()).append(" day(s)\n");
            }
            ctx.append("\n");
        } catch (Exception e) {
            logger.error("Context section failed: pending leaves", e);
            ctx.append("== LEAVE - PENDING REQUESTS (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Leave balances ---
        try {
            List<LeaveBalance> allBalances = leaveBalanceRepository.findAll();
            int currentYear = java.time.LocalDate.now().getYear();
            Map<String, List<LeaveBalance>> byType = allBalances.stream()
                    .filter(b -> b.getYear() != null && b.getYear() == currentYear)
                    .collect(Collectors.groupingBy(LeaveBalance::getLeaveType));

            ctx.append("== LEAVE BALANCES (company-wide, ").append(currentYear).append(") ==\n");
            for (var entry : byType.entrySet()) {
                double totalUsed = entry.getValue().stream()
                        .mapToDouble(b -> b.getUsedDays() != null ? b.getUsedDays() : 0.0).sum();
                double totalRemaining = entry.getValue().stream()
                        .mapToDouble(b -> b.getRemainingDays() != null ? b.getRemainingDays() : 0.0).sum();
                ctx.append(" - ").append(entry.getKey())
                        .append(": used ").append(totalUsed)
                        .append(", remaining ").append(totalRemaining)
                        .append(" (across ").append(entry.getValue().size()).append(" employees)\n");
            }
            ctx.append("\n");
        } catch (Exception e) {
            logger.warn("Could not load company-wide leave balances: {}", e.getMessage());
            ctx.append("== LEAVE BALANCES (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Recruitment ---
        try {
            List<Job> activeJobs = jobService.getActiveJobs();
            List<JobApplication> allApplications = jobApplicationService.getAllApplications();
            Map<Long, Long> appCountByJobId = allApplications.stream()
                    .filter(a -> a.getJob() != null)
                    .collect(Collectors.groupingBy(a -> a.getJob().getId(), Collectors.counting()));

            ctx.append("== RECRUITMENT ==\n");
            ctx.append("Open job postings: ").append(activeJobs.size()).append("\n");
            ctx.append("Total applications (all jobs): ").append(allApplications.size()).append("\n");
            for (Job j : activeJobs) {
                long count = appCountByJobId.getOrDefault(j.getId(), 0L);
                ctx.append(" - ").append(j.getTitle())
                        .append(" (").append(j.getDepartment()).append(", ").append(j.getLocation()).append(")")
                        .append(": ").append(count).append(" application(s)\n");
            }
            Map<String, Long> byStatus = allApplications.stream()
                    .filter(a -> a.getStatus() != null)
                    .collect(Collectors.groupingBy(JobApplication::getStatus, Collectors.counting()));
            ctx.append("Applications by stage:\n");
            byStatus.forEach((status, count) -> ctx.append(" - ").append(status).append(": ").append(count).append("\n"));
            ctx.append("\n");
        } catch (Exception e) {
            logger.error("Context section failed: recruitment", e);
            ctx.append("== RECRUITMENT (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Offers ---
        try {
            List<OfferLetter> allOffers = offerService.getAllOfferLetters();
            ctx.append("== OFFERS ==\n");
            ctx.append("Total offers generated: ").append(allOffers.size()).append("\n\n");
        } catch (Exception e) {
            logger.error("Context section failed: offers", e);
            ctx.append("== OFFERS (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Departments ---
        try {
            List<Department> departments = departmentService.getAllDepartments();
            ctx.append("== DEPARTMENTS ==\n");
            ctx.append("Total departments: ").append(departments.size()).append("\n\n");
        } catch (Exception e) {
            logger.error("Context section failed: departments", e);
            ctx.append("== DEPARTMENTS (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Holidays ---
        try {
            List<Holiday> upcomingHolidays = holidayService.getUpcomingHolidays();
            ctx.append("== UPCOMING HOLIDAYS ==\n");
            for (Holiday h : upcomingHolidays) {
                ctx.append(" - ").append(h.getHolidayName()).append(" on ").append(h.getHolidayDate()).append("\n");
            }
            ctx.append("\n");
        } catch (Exception e) {
            logger.error("Context section failed: holidays", e);
            ctx.append("== UPCOMING HOLIDAYS (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Employee documents ---
        try {
            List<OnboardingDocument> allDocs = onboardingDocumentRepository.findAll();
            Map<String, Long> docsByStatus = allDocs.stream()
                    .filter(d -> d.getStatus() != null)
                    .collect(Collectors.groupingBy(OnboardingDocument::getStatus, Collectors.counting()));

            ctx.append("== EMPLOYEE DOCUMENTS ==\n");
            ctx.append("Total document records: ").append(allDocs.size()).append("\n");
            docsByStatus.forEach((status, count) -> ctx.append(" - ").append(status).append(": ").append(count).append("\n"));

            List<String> unverifiedMandatory = allDocs.stream()
                    .filter(d -> d.isMandatory() && !"VERIFIED".equalsIgnoreCase(d.getStatus()))
                    .filter(d -> d.getEmployee() != null)
                    .map(d -> {
                        String name = d.getEmployee().getEmployeeName() != null
                                ? d.getEmployee().getEmployeeName() : d.getEmployee().getEmployeeId();
                        return name + " - " + d.getDocumentName() + " (" + d.getStatus() + ")";
                    })
                    .distinct()
                    .collect(Collectors.toList());

            ctx.append("Employees with unverified mandatory documents (").append(unverifiedMandatory.size()).append("):\n");
            for (String line : unverifiedMandatory) {
                ctx.append(" - ").append(line).append("\n");
            }
            ctx.append("\n");
        } catch (Exception e) {
            logger.warn("Could not load document status: {}", e.getMessage());
            ctx.append("== EMPLOYEE DOCUMENTS (unavailable: ").append(e.getMessage()).append(") ==\n\n");
        }

        // --- Announcements ---
        try {
            var announcements = announcementService.getAllAnnouncementsForAdmin();
            ctx.append("== EXISTING ANNOUNCEMENTS (read-only, do not draft new ones) ==\n");
            ctx.append("Currently posted: ").append(announcements.size()).append("\n");
        } catch (Exception e) {
            logger.error("Context section failed: announcements", e);
            ctx.append("== EXISTING ANNOUNCEMENTS (unavailable: ").append(e.getMessage()).append(") ==\n");
        }

        return ctx.toString();
    }
