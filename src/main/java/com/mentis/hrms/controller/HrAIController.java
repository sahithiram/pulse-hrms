    // Matches leave IDs generated by LeaveRequest.generateLeaveId(), e.g. LV-2026-1234
    private static final Pattern LEAVE_ID_PATTERN = Pattern.compile("(LV-\\d{4}-\\d{3,6})", Pattern.CASE_INSENSITIVE);
    // Matches employee IDs like EMP004
    private static final Pattern EMP_ID_PATTERN = Pattern.compile("\\b(EMP\\d+)\\b", Pattern.CASE_INSENSITIVE);
    private static final Set<String> LEAVE_TYPE_WORDS = Set.of("sick", "casual", "earned");
    private static final Set<String> INFORMATIONAL_STARTERS = Set.of(
            "what", "who", "which", "how", "give me", "show", "show me", "list",
            "summarize", "summary", "tell me", "can you tell", "could you tell",
            "display", "explain", "describe", "is there", "are there");

    private boolean isInformationalQuery(String lowerTrimmedMsg) {
        for (String starter : INFORMATIONAL_STARTERS) {
            if (lowerTrimmedMsg.startsWith(starter)) return true;
        }
        return false;
    }

    private boolean containsWord(String text, String word) {
        return Pattern.compile("\\b" + Pattern.quote(word) + "\\b", Pattern.CASE_INSENSITIVE)
                .matcher(text).find();
    }
    private record LeaveActionClause(String action, String leaveId, String employeeId,
                                     String leaveType, boolean remaining, String reason) {}

    /**
     * Parses one or more leave actions out of a single HR message. Supports:
     *  - an explicit leave ID ("approve LV-2026-1234")
     *  - a leave type ("approve sick leave")
     *  - an employee ID ("approve leave for EMP004")
     *  - "remaining/other/rest" to mean "everything still pending after the other clauses in
     *    this same message" (e.g. "approve sick leave and reject remaining leaves")
     * Compound instructions are split on " and ". Each clause needs an action verb (approve/
     * reject/deny) AND at least one way to target a leave, otherwise it's skipped - this keeps
     * generic questions ("how many leaves are pending") from being treated as commands.
     */
    private List<LeaveActionClause> parseLeaveActionClauses(String message) {
        String lower = message.toLowerCase().trim();
        if (message.trim().endsWith("?") || isInformationalQuery(lower)) {
            return List.of();
        }
        boolean mentionsVerb = containsWord(lower, "approve") || containsWord(lower, "reject") || containsWord(lower, "deny");
        boolean mentionsLeave = containsWord(lower, "leave");
        if (!mentionsVerb || !mentionsLeave) {
            return List.of();
        }

        String[] rawClauses = message.split("(?i)\\s+and\\s+");
        List<LeaveActionClause> clauses = new ArrayList<>();

        for (String raw : rawClauses) {
            String clauseLower = raw.toLowerCase();
            String action = null;
            if (clauseLower.contains("approve")) {
                action = "APPROVE";
            } else if (clauseLower.contains("reject") || clauseLower.contains("deny")) {
                action = "REJECT";
            }
            if (action == null) {
                continue; // this clause doesn't itself carry an action verb
            }

            Matcher idMatcher = LEAVE_ID_PATTERN.matcher(raw);
            String leaveId = idMatcher.find() ? idMatcher.group(1).toUpperCase() : null;

            Matcher empMatcher = EMP_ID_PATTERN.matcher(raw);
            String employeeId = empMatcher.find() ? empMatcher.group(1).toUpperCase() : null;

            String leaveType = null;
            for (String t : LEAVE_TYPE_WORDS) {
                if (clauseLower.contains(t)) {
                    leaveType = t;
                    break;
                }
            }

            boolean remaining = clauseLower.contains("remaining") || clauseLower.contains("rest of")
                    || clauseLower.contains("all other") || clauseLower.contains("other leave")
                    || clauseLower.contains("everything else") || clauseLower.contains(" rest");

            if (leaveId == null && employeeId == null && leaveType == null && !remaining) {
                continue; // no way to target a leave - too ambiguous, skip this clause
            }

            String reason = null;
            int reasonIdx = clauseLower.indexOf("reason:");
            if (reasonIdx == -1) {
                reasonIdx = clauseLower.indexOf("because");
            }
            if (reasonIdx != -1) {
                reason = raw.substring(reasonIdx).replaceFirst("(?i)^(reason:|because)", "").trim();
                if (reason.isEmpty()) {
                    reason = null;
                }
            }

            clauses.add(new LeaveActionClause(action, leaveId, employeeId, leaveType, remaining, reason));
        }
        return clauses;
    }

    /**
     * Resolves each clause against the current PENDING leave list and executes the action.
     * Specific clauses (explicit ID / type / employee) are applied first; "remaining" clauses
     * are applied afterward to whatever pending leaves are still untouched.
     */
    private String executeLeaveActionClauses(List<LeaveActionClause> clauses, String approverId) {
        List<LeaveRequest> pending = leaveRequestRepository.findByStatus("PENDING");
        Set<String> handledIds = new HashSet<>();
        StringBuilder reply = new StringBuilder();
        int actedCount = 0;

        for (LeaveActionClause clause : clauses) {
            if (clause.remaining()) continue;
            List<LeaveRequest> targets = pending.stream()
                    .filter(l -> !handledIds.contains(l.getId()))
                    .filter(l -> clause.leaveId() == null || clause.leaveId().equalsIgnoreCase(l.getId()))
                    .filter(l -> clause.employeeId() == null || clause.employeeId().equalsIgnoreCase(l.getEmployeeId()))
                    .filter(l -> clause.leaveType() == null || clause.leaveType().equalsIgnoreCase(l.getLeaveType()))
                    .collect(Collectors.toList());

            if (targets.isEmpty()) {
                reply.append("⚠️ Couldn't find a matching pending leave to ")
                        .append(clause.action().toLowerCase()).append(".\n");
                continue;
            }
            for (LeaveRequest lr : targets) {
                handledIds.add(lr.getId());
                actedCount++;
                appendLeaveActionResult(reply, clause, lr, approverId);
            }
        }

        for (LeaveActionClause clause : clauses) {
            if (!clause.remaining()) continue;
            List<LeaveRequest> targets = pending.stream()
                    .filter(l -> !handledIds.contains(l.getId()))
                    .collect(Collectors.toList());

            if (targets.isEmpty()) {
                reply.append("No other pending leaves needed action.\n");
                continue;
            }
            for (LeaveRequest lr : targets) {
                handledIds.add(lr.getId());
                actedCount++;
                appendLeaveActionResult(reply, clause, lr, approverId);
            }
        }

        if (actedCount == 0) {
            return "I couldn't find any matching pending leave requests to act on. " +
                    "Try mentioning the leave type (sick/casual/earned), an employee ID (e.g. EMP004), " +
                    "or the exact leave ID (e.g. LV-2026-1234).";
        }
        return reply.toString().trim();
    }

    private void appendLeaveActionResult(StringBuilder reply, LeaveActionClause clause, LeaveRequest lr, String approverId) {
        Map<String, Object> result = "APPROVE".equals(clause.action())
                ? leaveActionService.approveLeave(lr.getId(), approverId, clause.reason())
                : leaveActionService.rejectLeave(lr.getId(), approverId, clause.reason());
        boolean ok = Boolean.TRUE.equals(result.get("success"));
        if (ok) {
            reply.append("APPROVE".equals(clause.action()) ? "✅ " : "🚫 ")
                    .append(lr.getEmployeeId()).append(" - ").append(lr.getLeaveType())
                    .append(" leave (").append(lr.getId()).append(") ")
                    .append("APPROVE".equals(clause.action()) ? "approved" : "rejected")
                    .append(".\n");
        } else {
            reply.append("⚠️ Could not ").append(clause.action().toLowerCase())
                    .append(" ").append(lr.getId()).append(": ").append(result.get("error")).append("\n");
        }
    }

    @PostMapping("/send")
    public ResponseEntity<Map<String, Object>> sendMessage(
            @RequestBody Map<String, Object> request,
            HttpSession session) {

        Map<String, Object> response = new HashMap<>();

        String role = (String) session.getAttribute("userRole");
        if (role == null || !ALLOWED_ROLES.contains(role)) {
            response.put("success", false);
            response.put("error", "Unauthorized - HR access required");
            return ResponseEntity.status(403).body(response);
        }

        try {
            String userId = (String) session.getAttribute("userId");
            String message = (String) request.get("message");
            Integer sessionId = request.get("sessionId") != null
                    ? Integer.valueOf(request.get("sessionId").toString()) : null;

            if (message == null || message.trim().isEmpty()) {
                response.put("success", false);
                response.put("error", "Message is required");
                return ResponseEntity.badRequest().body(response);
            }

            List<LeaveActionClause> leaveClauses = parseLeaveActionClauses(message);
            if (!leaveClauses.isEmpty()) {
                String reply = executeLeaveActionClauses(leaveClauses, userId);

                if (sessionId == null) {
                    sessionId = hrAISessionService.createHrSession(userId, message, reply);
                } else {
                    hrAISessionService.addMessageToSession(sessionId, message, reply);
                }

                response.put("success", true);
                response.put("reply", reply);
                response.put("sessionId", sessionId);
                return ResponseEntity.ok(response);
            }

            FileRequest fileRequest = detectFileRequest(message);
            if (fileRequest != null) {
                String downloadUrl = "/api/chat/hr/export?type=" + fileRequest.area + "&format=" + fileRequest.format;
                String reply = "Here's your " + capitalize(fileRequest.area) + " report as " +
                        fileRequest.format.toUpperCase() + ". Click below to download.";

                if (sessionId == null) {
                    sessionId = hrAISessionService.createHrSession(userId, message, reply);
                } else {
                    hrAISessionService.addMessageToSession(sessionId, message, reply);
                }

                response.put("success", true);
                response.put("reply", reply);
                response.put("sessionId", sessionId);
                response.put("downloadUrl", downloadUrl);
                return ResponseEntity.ok(response);
            }

            String context = buildHrContext();
            String reply = hrAIService.processHrChat(userId, message, context);

            if (sessionId == null) {
                sessionId = hrAISessionService.createHrSession(userId, message, reply);
            } else {
                hrAISessionService.addMessageToSession(sessionId, message, reply);
            }

            response.put("success", true);
            response.put("reply", reply);
            response.put("sessionId", sessionId);

        } catch (Exception e) {
            logger.error("Error in HR AI chat: {}", e.getMessage(), e);
            response.put("success", false);
            response.put("error", e.getMessage());
        }

        return ResponseEntity.ok(response);
    }

